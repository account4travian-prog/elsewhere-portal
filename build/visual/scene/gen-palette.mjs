// Elsewhere Portal — scene palette generator (M4.07).
//
// palette.mjs is a GENERATED serialisation of the design tokens
// (build/visual/tokens/tokens.json — the one shipped source of colour,
// Visual Plan REC-1). The scene consumes colour ONLY through the
// generated palette: no family colour, anchor, or rig value is
// hard-coded in scene code. Change tokens.json, re-run this generator,
// commit both.
//
// Usage:
//   node gen-palette.mjs           regenerate palette.mjs in place
//   node gen-palette.mjs --check   exit 1 if palette.mjs differs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = join(here, '..', 'tokens', 'tokens.json');
export const PALETTE_MJS = join(here, 'palette.mjs');

export function buildPalette(doc = JSON.parse(readFileSync(TOKENS_JSON, 'utf8'))) {
  const byName = new Map();
  for (const g of Object.values(doc.groups)) for (const t of g.tokens) byName.set(t.name, t);
  const need = (name) => {
    const t = byName.get(name);
    if (!t) throw new Error(`gen-palette: token ${name} missing from tokens.json`);
    return t;
  };
  const val = (name) => need(name).value ?? need(name).hex;

  const anchors = {};
  for (const t of doc.groups['color.anchor'].tokens) {
    anchors[t.name.replace('color.anchor.', '')] = t.value;
  }
  const families = {};
  const familyForPlace = {};
  for (const t of doc.groups['material.family'].tokens) {
    const fam = t.name.replace('material.family.', '');
    families[fam] = { roles: t.roles, roleSources: t.roleSources };
    for (const code of t.places) familyForPlace[code] = fam;
  }
  const rigToken = (n) => val(`rig.${n}`);
  const rig = {
    sunColor: rigToken('sun.color'), sunIntensity: rigToken('sun.intensity'),
    hemiSky: rigToken('hemi.sky'), hemiGround: rigToken('hemi.ground'), hemiIntensity: rigToken('hemi.intensity'),
    fillColor: rigToken('fill.color'), fillIntensity: rigToken('fill.intensity'),
    fogColor: rigToken('fog.color'), fogNear: rigToken('fog.near'), fogFar: rigToken('fog.far'),
    exposure: rigToken('exposure'), gradientTexels: need('rig.gradientMap').value,
    blobShadowAlpha: rigToken('blobShadowAlpha'), skyDomeStops: need('rig.skyDomeStops').value,
    camera: {
      elevationDeg: Number(String(rigToken('camera.elevation')).replace('deg', '')),
      followFovDeg: Number(rigToken('camera.followFov')),
      overviewFrustumHeight: Number(need('rig.camera.overviewFrustumHeight').values.asBuilt),
    },
  };
  const state = { conflictBorder: val('color.state.conflictBorder') };
  const cameraWordings = {};
  for (const t of doc.groups.wording?.tokens || []) {
    if (t.name.startsWith('wording.camera.')) {
      cameraWordings[t.name.replace('wording.camera.', '')] = t.value;
    }
  }

  const out = {
    anchors, families, familyForPlace, defaultFamily: 'home', rig, state, cameraWordings,
  };
  const body = `// GENERATED by gen-palette.mjs from build/visual/tokens/tokens.json.
// Do not edit by hand: change the tokens, re-run the generator, commit both.
// Colour authority: sampled palette anchors govern over plan constants (AUTO-L04).

export const PALETTE = ${JSON.stringify(out, null, 2)};

export const ANCHORS = PALETTE.anchors;
export const FAMILIES = PALETTE.families;
export const RIG_TOKENS = PALETTE.rig;
export const CAMERA_WORDINGS = PALETTE.cameraWordings;

/** The material family a place code is treated with (tokens-defined). */
export function familyForPlace(code) {
  return PALETTE.familyForPlace[code] || PALETTE.defaultFamily;
}
`;
  return body;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const body = buildPalette();
  if (process.argv.includes('--check')) {
    const current = readFileSync(PALETTE_MJS, 'utf8');
    if (current !== body) {
      console.error('palette.mjs is stale — regenerate with: node gen-palette.mjs');
      process.exit(1);
    }
    console.log('palette.mjs is byte-identical to a fresh regeneration.');
  } else {
    writeFileSync(PALETTE_MJS, body);
    console.log(`palette.mjs regenerated (${body.length} bytes).`);
  }
}
